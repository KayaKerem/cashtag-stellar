// Usage: npm i canonicalize@2 && node fixtures/reclaim/gen-required-substrings.mjs config/providers.json > fixtures/required-substrings.json
// Re-run whenever config/providers.json changes.
import canonicalize from 'canonicalize'
import fs from 'fs'
const cfg = JSON.parse(fs.readFileSync(process.argv[2], 'utf8'))
const out = { _note: "Exact byte strings that appear inside canonical claimData.parameters (JCS). cliprail passes each entry of `required` to reclaim_verify::verify; `urlNeedleExample` shows the needle verify builds from expected_url (\"url\":\"<expected_url>\"). Generated by fixtures/reclaim/gen-required-substrings.mjs from config/providers.json." }
for (const [name, p] of Object.entries(cfg)) {
  out[name] = {
    required: p.responseMatches.map(m => canonicalize({ type: m.type, value: m.value })),
    regexValues: p.responseMatches.map(m => m.value),
    urlNeedleExample: canonicalize({ url: p.urlPrefix + 'VIDEO_ID' + p.urlSuffix }).slice(1, -1),
  }
}
console.log(JSON.stringify(out, null, 2))
